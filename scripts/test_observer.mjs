import assert from 'node:assert/strict';
import { QualityObserver } from '../runtime/quality.mjs';
const observer = new QualityObserver({ maxMessagesPerHook: 1 });
const texts = ['行，先看看端口。', '未覆盖的第二条仍需保留。'];
const result = observer.inspect(texts, { sessionKey: 'A' });
assert.deepEqual(result.messages, texts);
assert.equal(result.inspected, 1);
assert.equal(observer.history.size, 0);
assert.ok(['PASS', 'WARN'].includes(result.action));
observer.confirmDelivered('A', ['确实如此。', '确实没错。']);
assert.ok(observer.inspect(['确实是这样。'], { sessionKey: 'A' }).flags.some(f => f.code === 'RECENT_ACT_REUSE'));
assert.ok(!observer.inspect(['确实是这样。'], { sessionKey: 'B' }).flags.some(f => f.code === 'RECENT_ACT_REUSE'));
observer.clear('A');
assert.equal(observer.history.size, 0);
const off = new QualityObserver({ enabled: false });
off.confirmDelivered('A', ['确实如此。']);
assert.equal(off.history.size, 0);
assert.equal(off.inspect(texts).action, 'PASS');
console.log('Observer invariants passed: unchanged output, delivery-only memory, session isolation, disabled mode.');
